function expectRule(selector: string, declarations: RegExp) {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  expect(styles).toMatch(new RegExp(`${escaped}\\s*\\{[^}]*${declarations.source}[^}]*\\}`, 's'))
}

